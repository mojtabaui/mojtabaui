/**
 * گواهی‌های «with Distinction» — سطح بالای گواهی برای دانشجوهای خیلی فعال.
 *
 * عمداً ستون دیتابیس نیست: گواهی هر دوره یک بار صادر می‌شه و سطحش بعد از
 * اون عوض نمی‌شه، پس یک فهرست ثابت کافیه و لازم نیست به دیتابیس زنده دست
 * بزنیم. فقط کد گواهی‌ها اینجاست، نه اسم‌ها، چون ریپو عمومیه.
 *
 * عمداً درصد هم نیست («top 5%»): کلاس‌ها حدود سی نفره‌ان و ادعای عددی روی
 * سندی که کارفرما استعلامش می‌کنه باید واقعاً درست باشه.
 */
const DISTINCTION_CODES = new Set<string>([
  // کوادکمپ، پاییز ۱۴۰۴ — همه به‌جز QC0009، QC0013 و QC0031
  "QC0007", "QC0008", "QC0010", "QC0011", "QC0012", "QC0014", "QC0015",
  "QC0016", "QC0017", "QC0018", "QC0019", "QC0020", "QC0021", "QC0022",
  "QC0023", "QC0024", "QC0025", "QC0026", "QC0027", "QC0028", "QC0029",
  "QC0030", "QC0032", "QC0033", "QC0034", "QC0035", "QC0036", "QC0037",
  "QC0038", "QC0039", "QC0040",
]);

export function isDistinction(code: string): boolean {
  return DISTINCTION_CODES.has(code.trim().toUpperCase());
}
